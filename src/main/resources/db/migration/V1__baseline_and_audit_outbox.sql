CREATE TABLE trade_report (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount              NUMERIC(38, 2) NOT NULL,
    firm                VARCHAR(255)   NOT NULL,
    created_on          TIMESTAMPTZ,
    updated_on          TIMESTAMPTZ,
    trade_report_status VARCHAR(255),
    version             BIGINT
);

CREATE TABLE trade_reports_audits (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id            UUID         NOT NULL,
    trade_report_id     BIGINT       REFERENCES trade_report (id),
    report_version      BIGINT,
    changed_by          VARCHAR(255),
    audit_time          TIMESTAMPTZ,
    trade_report_status VARCHAR(255),
    CONSTRAINT uq_audit_event_id UNIQUE (event_id)
);

CREATE INDEX idx_audit_trade_report_id ON trade_reports_audits (trade_report_id);

-- Audit rows are append-only (regulatory requirement): block UPDATE / DELETE at the DB level.
CREATE FUNCTION forbid_audit_mutation() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'trade_reports_audits is append-only';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_immutable
    BEFORE UPDATE OR DELETE ON trade_reports_audits
    FOR EACH ROW EXECUTE FUNCTION forbid_audit_mutation();

CREATE TABLE outbox_event (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id            UUID           NOT NULL UNIQUE,
    report_id           BIGINT         NOT NULL,
    report_version      BIGINT         NOT NULL,
    amount              NUMERIC(38, 2) NOT NULL,
    firm                VARCHAR(255)   NOT NULL,
    report_created_on   TIMESTAMPTZ    NOT NULL,
    event_type          VARCHAR(255)   NOT NULL,
    changed_by          VARCHAR(255),
    occurred_at         TIMESTAMPTZ    NOT NULL,
    published_at        TIMESTAMPTZ
);
CREATE INDEX idx_outbox_unpublished ON outbox_event (id) WHERE published_at IS NULL;
